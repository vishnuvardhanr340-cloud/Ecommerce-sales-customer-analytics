CREATE TABLE raw_orders (
    order_id VARCHAR(50),
    order_date DATE,
    order_time TIME,
    order_status VARCHAR(50),
    sales_channel VARCHAR(50),
    customer_id VARCHAR(50),
    customer_name VARCHAR(150),
    customer_age INT,
    gender VARCHAR(20),
    customer_segment VARCHAR(50),
    customer_type VARCHAR(50),
    customer_city VARCHAR(150),
    customer_state VARCHAR(150),
    customer_country VARCHAR(100),
    region VARCHAR(50),
    customer_postal_code VARCHAR(30),
    payment_method VARCHAR(100),
    payment_status VARCHAR(50),
    currency VARCHAR(10),
    shipping_method VARCHAR(50),
    warehouse VARCHAR(50),
    delivery_days DECIMAL(10,2),
    estimated_delivery_days DECIMAL(10,2),
    delivery_status VARCHAR(50),
    return_status VARCHAR(50),
    return_reason VARCHAR(200),
    customer_rating DECIMAL(4,2),
    review_sentiment VARCHAR(50),
    customer_review TEXT,
    marketing_channel VARCHAR(100),
    campaign_name VARCHAR(150),
    coupon_code VARCHAR(50),
    loyalty_points_earned INT,
    loyalty_points_redeemed INT,
    quantity INT,
    gross_sales DECIMAL(14,2),
    discount_amount DECIMAL(14,2),
    tax_amount DECIMAL(14,2),
    shipping_cost DECIMAL(14,2),
    net_sales DECIMAL(14,2),
    product_cost DECIMAL(14,2),
    profit DECIMAL(14,2),
    profit_margin_percentage DECIMAL(10,2),
    customer_lifetime_value DECIMAL(14,2),
    is_repeat_customer BOOLEAN,
    customer_order_count INT
);

CREATE TABLE raw_customers (
    customer_id VARCHAR(50),
    customer_name VARCHAR(150),
    customer_age INT,
    gender VARCHAR(20),
    customer_segment VARCHAR(50),
    customer_city VARCHAR(150),
    customer_state VARCHAR(150),
    customer_country VARCHAR(100),
    region VARCHAR(50),
    customer_postal_code VARCHAR(30),
    customer_acquisition_cost DECIMAL(12,2)
);

CREATE TABLE raw_products (
    product_id VARCHAR(50),
    product_name VARCHAR(250),
    product_category VARCHAR(100),
    product_subcategory VARCHAR(100),
    brand VARCHAR(100),
    supplier VARCHAR(150),
    unit_price DECIMAL(12,2),
    product_cost DECIMAL(12,2),
    product_rating DECIMAL(4,2)
);

CREATE TABLE raw_order_items (
    order_id VARCHAR(50),
    product_id VARCHAR(50),
    quantity INT,
    unit_price DECIMAL(12,2),
    discount_percentage DECIMAL(10,6),
    discount_amount DECIMAL(14,2),
    gross_sales DECIMAL(14,2),
    tax_amount DECIMAL(14,2),
    shipping_cost DECIMAL(14,2),
    net_sales DECIMAL(14,2),
    product_cost DECIMAL(14,2),
    profit DECIMAL(14,2)
);
